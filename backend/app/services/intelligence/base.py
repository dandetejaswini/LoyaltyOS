import hashlib
from abc import ABC, abstractmethod
from decimal import Decimal
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, ConfigDict
from sqlalchemy.ext.asyncio import AsyncSession


class AnomalyFinding(BaseModel):
    """
    Normalized explainable anomaly representation generated by any LLIRE detector.
    """
    model_config = ConfigDict(arbitrary_types_allowed=True)

    detector_id: str
    category: str
    entity_type: str
    entity_id: str
    variance_amount: Decimal
    severity: str  # CRITICAL, HIGH, MEDIUM, LOW
    severity_reason: str
    rule_violated: str
    what_happened: str
    description: str
    evidence: Dict[str, Any]
    discrepancy_calculation: Dict[str, Any]
    recommendation: str
    fingerprint: Optional[str] = None

    def model_post_init(self, __context: Any) -> None:
        if not self.fingerprint:
            # Deterministic, collision-resistant fingerprint for idempotency
            raw = f"{self.detector_id}:{self.category}:{self.entity_type}:{self.entity_id}:{self.variance_amount}"
            self.fingerprint = hashlib.sha256(raw.encode("utf-8")).hexdigest()[:16]

    def to_details_payload(self) -> Dict[str, Any]:
        """
        Converts finding attributes into structured details payload for JSONB storage.
        """
        return {
            "detector_id": self.detector_id,
            "category": self.category,
            "severity": self.severity,
            "severity_reason": self.severity_reason,
            "rule_violated": self.rule_violated,
            "what_happened": self.what_happened,
            "description": self.description,
            "evidence": self.evidence,
            "discrepancy_calculation": self.discrepancy_calculation,
            "recommendation": self.recommendation,
            "fingerprint": self.fingerprint,
        }


class BaseDetector(ABC):
    """
    Abstract base contract for all LLIRE detectors.
    Ensures consistent execution, explainability, evidence generation, and reporting.
    """

    def __init__(self, detector_id: str, category: str, name: str):
        self.detector_id = detector_id
        self.category = category
        self.name = name

    @abstractmethod
    async def detect(
        self,
        db: AsyncSession,
        account_id: Optional[str] = None,
        **kwargs
    ) -> List[AnomalyFinding]:
        """
        Execute detection rules against source database records.
        Returns a list of explainable AnomalyFinding instances.
        """
        pass
